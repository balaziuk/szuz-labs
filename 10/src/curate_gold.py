def main():
    docs = {json.loads(ln)["doc_id"]: json.loads(ln) for ln in
            (ROOT / "data" / "documents.jsonl").read_text(encoding="utf-8").splitlines()}
    dtext = {k: norm(" ".join(" ".join(p) for _, p in d["sections"])) for k, d in docs.items()}
    cands = [json.loads(ln) for ln in (ROOT / "eval" / "candidates.jsonl").read_text(encoding="utf-8").splitlines()]

    gold, review_log, errors = [], [], []

    def add(query, qtype, answers, origin):
        for doc_id, span in answers:
            if norm(span) not in dtext[doc_id]:
                errors.append(f"{query[:50]} :: span не знайдено в {doc_id}: {span}")
        gold.append({"qid": f"Q{len(gold) + 1:02d}", "query": query, "type": qtype,
                     "answers": [{"doc_id": d, "span": s} for d, s in answers], "origin": origin})

    for c in cands:
        decision, reason, edits = REVIEW[c["chunk_id"]]
        review_log.append({"chunk_id": c["chunk_id"], "decision": decision, "reason": reason,
                           "llm": {k: c.get(k) for k in ("keyword", "paraphrase", "answer_quote")},
                           "edits": edits})
        if decision == "reject":
            continue
        c = {**c, **edits}
        origin = "llm_accepted" if decision == "accept" else "llm_edited"
        add(c["keyword"], "keyword", [(c["doc_id"], c["answer_quote"])], origin)
        add(c["paraphrase"], "paraphrase", [(c["doc_id"], c["answer_quote"])], origin)
    for q, t, ans in MANUAL:
        add(q, t, ans, "manual")
    for q, ans in MULTIHOP:
        add(q, "multihop", ans, "manual")
    for q, banned in NO_ANSWER:
        for b in banned:
            hits = [k for k, t in dtext.items() if b in t]
            if hits:
                errors.append(f"запит без відповіді «{q}»: фраза «{b}» є в {hits}")
        add(q, "no_answer", [], "manual")

    if errors:
        print("\n".join(errors))
        raise SystemExit("є помилки в золотому наборі")

    with open(ROOT / "eval" / "gold.jsonl", "w", encoding="utf-8") as f:
        for g in gold:
            f.write(json.dumps(g, ensure_ascii=False) + "\n")
    (ROOT / "llm_log").mkdir(exist_ok=True)
    with open(ROOT / "llm_log" / "gen_questions_review.jsonl", "w", encoding="utf-8") as f:
        for r in review_log:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    from collections import Counter
    print("запитів:", len(gold), Counter(g["type"] for g in gold), Counter(g["origin"] for g in gold))
    print("рішення щодо кандидатів LLM:", Counter(r["decision"] for r in review_log))


if __name__ == "__main__":
    main()
